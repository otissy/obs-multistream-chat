<#
 Fetches the headers and libs this plugin builds against, hash-pinned, into .obs-sdk\ and .qt-sdk\
 (both gitignored). Sources: official OBS Studio 32.2.2 source tag and obs-deps Qt6 2026-07-15.
 Downloads are throttled (5 MB/s) and refuse to continue on any hash mismatch. TLS verification is
 never disabled. If an antivirus re-signs HTTPS, point curl at a PEM of the Windows root store:
   $env:SSL_CERT_FILE = 'C:\path\to\windows-roots.pem'
#>
[CmdletBinding()]
param([string]$Root = (Split-Path -Parent $PSScriptRoot), [string]$Cache = (Join-Path (Split-Path -Parent $PSScriptRoot) 'build\downloads'))
$ErrorActionPreference = 'Stop'

$ObsUrl  = 'https://github.com/obsproject/obs-studio/archive/refs/tags/32.2.2.tar.gz'
$ObsSha  = '35d3cd0979d65664fada7119fdb612eca7c34b61a1623a330caec74bf72626c4'
$QtUrl   = 'https://github.com/obsproject/obs-deps/releases/download/2026-07-15/windows-deps-qt6-2026-07-15-x64.zip'
$QtSha   = '7c7f985711d80467bdc1795b6592275a27d5b0e5a2c7a61db1f2c1d08d6a5579'

function Get-Pinned([string]$Url, [string]$Sha, [string]$Name) {
  New-Item -ItemType Directory -Force $Cache | Out-Null
  $dest = Join-Path $Cache $Name
  if (-not (Test-Path $dest) -or (Get-FileHash $dest -Algorithm SHA256).Hash.ToLower() -ne $Sha) {
    Write-Host "downloading $Name"
    $args = @('-sSL', '--fail', '--limit-rate', '5M', '-o', $dest, $Url)
    if ($env:SSL_CERT_FILE) { $args = @('--cacert', $env:SSL_CERT_FILE) + $args }
    & curl.exe @args
    if ($LASTEXITCODE -ne 0) { throw "download failed: $Url" }
  }
  $got = (Get-FileHash $dest -Algorithm SHA256).Hash.ToLower()
  if ($got -ne $Sha) { Remove-Item $dest -Force; throw "SHA-256 mismatch for $Name`n expected $Sha`n got      $got" }
  Write-Host "verified $Name ($Sha)"
  return $dest
}

# ---- OBS headers ---------------------------------------------------------------------------
$obsDir = Join-Path $Root '.obs-sdk'
if (-not (Test-Path (Join-Path $obsDir 'libobs\obs-module.h'))) {
  $tgz = Get-Pinned $ObsUrl $ObsSha 'obs-studio-32.2.2.tar.gz'
  $tmp = Join-Path $Cache 'obs-src'
  Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
  New-Item -ItemType Directory -Force $tmp | Out-Null
  & tar.exe -xzf $tgz -C $tmp --wildcards '*/libobs/*' '*/frontend/api/*'
  if ($LASTEXITCODE -ne 0) { throw 'tar failed' }
  $src = Get-ChildItem $tmp -Directory | Select-Object -First 1
  New-Item -ItemType Directory -Force (Join-Path $obsDir 'libobs'), (Join-Path $obsDir 'frontend-api'), (Join-Path $obsDir 'lib') | Out-Null
  Copy-Item (Join-Path $src.FullName 'libobs\*') (Join-Path $obsDir 'libobs') -Recurse -Force
  Copy-Item (Join-Path $src.FullName 'frontend\api\*') (Join-Path $obsDir 'frontend-api') -Recurse -Force
  Get-ChildItem $obsDir -Recurse -File | Where-Object { $_.Extension -notin '.h', '.hpp', '.lib' } | Remove-Item -Force
  # obsconfig.h is generated by OBS's CMake; this stand-in is enough for plugin builds
  @'
#pragma once
#define OBS_DATA_PATH "../../data"
#define OBS_PLUGIN_PATH "../../obs-plugins/64bit"
#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"
#define OBS_INSTALL_PREFIX ""
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
'@ | Set-Content (Join-Path $obsDir 'libobs\obsconfig.h') -Encoding ascii
  Write-Host "OBS 32.2.2 headers -> $obsDir"
}

# ---- Qt (headers + import libs only) ---------------------------------------------------------
$qtDir = Join-Path $Root '.qt-sdk'
if (-not (Test-Path (Join-Path $qtDir 'lib\Qt6Widgets.lib'))) {
  $zip = Get-Pinned $QtUrl $QtSha 'windows-deps-qt6-2026-07-15-x64.zip'
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $za = [IO.Compression.ZipFile]::OpenRead($zip)
  try {
    foreach ($e in $za.Entries) {
      if ($e.FullName -match '^include/(QtCore|QtGui|QtWidgets)/' -or $e.FullName -match '^lib/Qt6(Core|Gui|Widgets)\.lib$') {
        if ($e.Name -eq '') { continue }
        $out = Join-Path $qtDir $e.FullName
        New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
        [IO.Compression.ZipFileExtensions]::ExtractToFile($e, $out, $true)
      }
    }
  } finally { $za.Dispose() }
  Write-Host "Qt 6.11.1 headers/libs -> $qtDir"
}
Write-Host 'SDKs ready. Next: scripts\build.ps1'
