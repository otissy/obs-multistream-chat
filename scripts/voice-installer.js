#!/usr/bin/env node
'use strict';
// Writes the voice part of the installer (packaging/voices.generated.iss, #included by installer.iss)
// from the packs that scripts/fetch-voices.js shipped (its manifest.json: licence-checked and pinned).
//   - embedded packs are staged in data\voices by scripts/package.ps1, so they are in the zip and the
//     setup alike (offline install): Kokoro, 54 voices in 8 languages including American and British English
//   - every other shipped pack is a component per language, unticked; Setup downloads the ones that
//     are ticked from the k2-fsa release, checks each against its pinned SHA-256, and unpacks it with
//     Windows' own tar.exe into {app}\data\voices
//
//   node scripts/voice-installer.js --manifest <fetch out>/manifest.json --out packaging/voices.generated.iss
//        [--embed id,id] [--catalogue voice/catalogue.json]
const fs = require('fs');
const path = require('path');
const { loadCatalogue } = require('../voice/lib/catalogue');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_EMBED = ['kokoro-multi-lang-v1_0'];

function parseArgs(argv) {
  const o = { catalogue: path.join(ROOT, 'voice', 'catalogue.json'), embed: DEFAULT_EMBED };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--manifest') o.manifest = argv[++i];
    else if (a === '--out') o.out = argv[++i];
    else if (a === '--embed') o.embed = argv[++i].split(',').filter(Boolean);
    else if (a === '--catalogue') o.catalogue = argv[++i];
    else throw new Error('unknown argument: ' + a);
  }
  if (!o.manifest || !o.out) throw new Error('--manifest and --out are required');
  return o;
}

// Inno component names: letters only, lower case ("Portuguese" -> "portuguese")
const compName = lang => 'voices\\' + lang.toLowerCase().replace(/[^a-z]/g, '');
const pas = s => "'" + String(s).replace(/'/g, "''") + "'";
const mb = bytes => Math.max(1, Math.round(bytes / 1e6));

function generate(cat, manifest, release, embed) {
  const shipped = new Map(manifest.shipped.map(s => [s.id, s]));
  const langOf = id => {
    const langs = [...new Set([...cat.voices.values()].filter(v => v.pack === id).map(v => v.language))];
    return langs.length === 1 ? langs[0] : null;
  };
  const embedded = embed.filter(id => shipped.has(id));
  const byLang = new Map(); // language -> [pack]
  for (const s of manifest.shipped) {
    if (embedded.includes(s.id)) continue;
    const lang = langOf(s.id);
    if (!lang) continue; // multi-language packs are only ever embedded
    if (!byLang.has(lang)) byLang.set(lang, []);
    byLang.get(lang).push(s);
  }
  const langs = [...byLang.keys()].sort();
  const embeddedLangs = [...new Set(embedded.flatMap(id => [...cat.voices.values()].filter(v => v.pack === id).map(v => v.language)))].sort();

  const L = [];
  L.push('; GENERATED by scripts/voice-installer.js from the fetch-voices manifest. Do not edit.');
  L.push('[Components]');
  L.push('Name: "voices"; Description: "Chat voices (neural, offline)"; Types: full compact custom; Flags: fixed');
  if (embedded.length) {
    L.push(`Name: "voices\\included"; Description: "Included: ${embeddedLangs.join(', ')}"; Types: full compact custom; Flags: fixed`);
  }
  for (const lang of langs) {
    const packs = byLang.get(lang);
    const bytes = packs.reduce((a, p) => a + (p.bytes || 0), 0);
    const accents = [...new Set([...cat.voices.values()].filter(v => packs.some(p => p.id === v.pack)).map(v => v.accent).filter(Boolean))];
    const what = lang + (accents.length ? ' (' + accents.slice(0, 4).join(', ') + ')' : '');
    // unticked by default (no Types): ticking one downloads it during setup
    L.push(`Name: "${compName(lang)}"; Description: "${what.replace(/"/g, "'")}: download, ${mb(bytes)} MB"; ExtraDiskSpaceRequired: ${Math.round(bytes * 1.3)}`);
  }
  L.push('');
  L.push('[UninstallDelete]');
  L.push('Type: filesandordirs; Name: "{app}\\data\\voices"');
  L.push('');
  L.push('[Code]');
  L.push('procedure ForEachVoicePack(Download: Boolean);');
  L.push('begin');
  for (const lang of langs) {
    L.push(`  if WizardIsComponentSelected(${pas(compName(lang))}) then begin`);
    for (const p of byLang.get(lang)) {
      L.push(`    if Download then AddVoiceDownload(${pas(release + p.id + '.tar.bz2')}, ${pas(p.id + '.tar.bz2')}, ${pas(p.sha256)})`);
      L.push(`    else ExtractVoicePack(${pas(p.id + '.tar.bz2')});`);
    }
    L.push('  end;');
  }
  L.push('end;');
  L.push('');
  return { text: L.join('\r\n'), embedded, languages: langs };
}

function main(argv) {
  const o = parseArgs(argv);
  const cat = loadCatalogue(o.catalogue);
  const release = JSON.parse(fs.readFileSync(o.catalogue, 'utf8')).release;
  const manifest = JSON.parse(fs.readFileSync(o.manifest, 'utf8'));
  for (const s of manifest.shipped) {
    if (!cat.packs.has(s.id)) throw new Error('manifest names a pack the catalogue does not: ' + s.id);
    if (!/^[0-9a-f]{64}$/.test(s.sha256 || '')) throw new Error('manifest pack without a SHA-256: ' + s.id);
  }
  const g = generate(cat, manifest, release, o.embed);
  fs.writeFileSync(o.out, '﻿' + g.text);
  process.stdout.write(`voices: ${g.embedded.length} packs embedded, ${g.languages.length} languages to download\n`);
  return g;
}

if (require.main === module) {
  try { main(process.argv.slice(2)); } catch (e) { process.stderr.write('voice-installer: ' + e.message + '\n'); process.exit(2); }
}

module.exports = { parseArgs, generate, main, DEFAULT_EMBED };
